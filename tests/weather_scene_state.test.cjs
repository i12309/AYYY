'use strict';
const assert=require('node:assert/strict');
global.AYYYWeatherModel=require('../weather/model.js');
global.AYYYTreePalette=require('../weather/tree-palette.js');
const S=require('../weather/scene-state.js'),M=global.AYYYWeatherModel;
const data=M.demo(M.CITIES[1],Date.parse('2026-11-08T09:00:00Z'));
const point={...data.current,code:61,precip:1,interval:900,precipUnit:'mm',wind:0,clouds:0};
const build=(p=point,override={})=>S.build(data,p,p.time,override,{},p.time);
assert.equal(build().precipitationRate,4);
assert.equal(build({...point,interval:3600}).precipitationRate,1);
assert.equal(build({...point,interval:null}).precipitationRate,null);
assert.equal(build({...point,precipUnit:null}).precipitationRate,null);
assert.equal(build({...point,precip:null}).precipitationRate,null);
assert.equal(build({...point,code:0,pop:90,precip:0}).precipitationEffect,0);
assert.equal(build().windSpeed,0);assert.equal(build().cloudCover,0);
assert.equal(build({...point,code:null}).weather,'unknown');
assert.equal(build({...point,code:97}).weather,'storm');
assert.equal(build({...point,code:1}).weather,'partly');
const south=structuredClone(data);south.city.latitude=-34;
const a=build(),b=S.build(south,point,point.time);
assert.equal(a.calendarMonth,b.calendarMonth);assert.equal(b.seasonMonth,(a.seasonMonth+6)%12);
const polar=structuredClone(data);polar.days.forEach(d=>{d.sunrise=null;d.sunset=null});
assert.equal(S.build(polar,{...point,isDay:false},point.time).phase,'night');
assert.equal(S.build(polar,{...point,isDay:true},point.time).phase,'day');
const manual=build({...point,wind:20},{base:a,weather:'snow',month:0});
assert.equal(manual.source,'manual');assert.equal(manual.windSpeed,0);assert.equal(manual.snowCover,true);
assert.equal(build({...point,code:0}).snowCover,false);
assert.equal(build().observedAt,point.time);
assert.equal(S.build(data,point,null,{}, {},point.time+3600).sceneTime,point.time+3600);
assert.equal(S.build(data,point,point.time,{}, {},point.time+3600).sceneTime,point.time);
assert.equal(data.current.wind,4.1);
const clear={...point,code:0};
const previewBase=build(clear);
const dusk=build(clear,{base:previewBase,weather:'clear',phase:'dusk'});
assert.equal(dusk.minute,1050);
assert.equal(build(clear,{base:previewBase,phase:'dawn'}).minute,458);
assert.deepEqual(dusk.light,global.AYYYTreePalette.atmosphere(global.AYYYTreePalette.lighting(1050),'clear'));
console.log('25 scene-state assertions PASS');
