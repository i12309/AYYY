'use strict';
const assert=require('node:assert/strict'),M=require('../markets/model.js'),C=require('../markets/chart.js');
let checks=0;function test(name,fn){fn();checks++;console.log('PASS',name);}
const now=Date.UTC(2026,10,6),rows=[];
for(let i=80;i>=0;i--){const date=M.dateKey(now-i*M.DAY);for(const [quote,rate] of Object.entries({USD:.01,EUR:.008,GBP:.007,CNY:.075,CHF:.009,JPY:1.5}))rows.push({date,base:'RUB',quote,rate});}
const d=M.parse(rows,now);
test('schema valid',()=>assert(M.valid(d,now)));
test('dates sorted and exact',()=>assert.equal(d.days.length,81));
test('inverse reference quote',()=>assert.equal(d.days[0].rates.USD,100));
test('cross currency uses common date',()=>assert.equal(M.convert(d,100,'USD','EUR').total,80));
test('ruble quote',()=>assert.equal(M.convert(d,2,'USD','RUB').total,200));
test('inverse ruble',()=>assert.equal(M.convert(d,100,'RUB','USD').total,1));
test('zero amount',()=>assert.equal(M.convert(d,0,'USD','RUB').total,0));
test('localized input',()=>assert.equal(M.convert(d,'1\u202f000,50','USD','RUB').total,100050));
for(const bad of ['-1','Infinity','2e5','0x10','<script>','1,2.3','',null,'1000000000001'])test('reject amount '+bad,()=>assert.throws(()=>M.convert(d,bad,'USD','RUB')));
test('reject unknown currency',()=>assert.throws(()=>M.convert(d,3,'BOGUS','RUB')));
test('missing data does not fabricate',()=>assert.throws(()=>M.convert(null,3,'USD','RUB')));
test('same currency value',()=>assert.equal(M.convert(d,8,'EUR','EUR').total,8));
const partial=JSON.parse(JSON.stringify(d));delete partial.days.at(-1).rates.EUR;
test('common-date conversion skips missing latest',()=>assert.equal(M.convert(partial,100,'USD','EUR').date,partial.days.at(-2).date));
test('history date cutoff',()=>assert.equal(M.series(d,'USD','RUB',30).length,31));
test('no unknown series',()=>assert.deepEqual(M.series(d,'ZZZ','RUB'),[]));
test('no empty stats invented',()=>assert.equal(M.stats([]),null));
const pp=M.series(d,'USD','RUB',80),s=M.stats(pp);
test('summary actual range',()=>assert.equal(s.percent,0));
test('summary count',()=>assert.equal(s.count,81));
test('moving average has warmup gap',()=>assert.equal(M.sma(pp,20)[18].value,null));
test('moving average constant',()=>assert.equal(M.sma(pp,20)[19].value,100));
test('Bollinger constant band',()=>assert.equal(M.bands(pp)[30].lower,100));
test('finite constant chart',()=>assert(!C.plot(pp,pp,{sma20:true,bb:true}).html.match(/NaN|Infinity/)));
test('no-data chart',()=>assert.equal(C.plot([],[]),null));
test('single-point chart finite',()=>assert(!C.plot(pp.slice(0,1),pp).html.match(/NaN|Infinity/)));
test('responsive chart dimensions',()=>assert.equal(C.plot(pp,pp,{width:1100,height:220}).W,1100));
test('unsafe date rejected',()=>assert(!M.validDate('2026-02-30')));
test('HTML date rejected',()=>assert(!M.validDate('<img>')));
test('future cache rejected',()=>assert(!M.valid({...d,updatedAt:now+120000},now)));
test('unknown schema rejected',()=>assert(!M.valid({...d,version:42},now)));
test('cache duplicate date rejected',()=>assert(!M.valid({...d,days:[d.days[0],d.days[0]]},now)));
test('nonpositive rate rejected',()=>assert.throws(()=>M.parse([{date:'2026-11-01',base:'RUB',quote:'USD',rate:0}],now)));
test('bad data rejected',()=>assert.throws(()=>M.parse({},now)));
test('API URL never includes amounts',()=>{const u=new URL(M.url(now));assert.equal(u.hostname,'api.frankfurter.dev');assert.equal(u.searchParams.get('base'),'rub');assert(!u.searchParams.has('amount'));});
test('widget is cross-origin, no inline executable source',()=>{const u=new URL(M.widgetURL('gold','6M'));assert.equal(u.origin,'https://s.tradingview.com');assert.equal(u.searchParams.get('range'),'6M');assert.equal(u.searchParams.get('symbol'),'OANDA:XAUUSD');});
test('widget restricted to defined instruments',()=>assert.throws(()=>M.widgetURL('https://evil.test')));
test('CSV has data only',()=>assert.equal(M.csv(pp).split('\r\n').length,82));
console.log(checks+' market model checks passed');
